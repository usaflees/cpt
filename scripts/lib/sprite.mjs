// Packs every coin-icons/<sym>.svg into one file, coin-icons/sprite.svg, so a page that shows many
// logos (home table, movers, tape, heatmap, sector hubs) makes one image request instead of one per coin.
// Googlebot renders pages with a very tall window, so lazy loading doesn't save it those requests: on
// the 12 Nov crawl stats about two thirds of its requests were images (docs/INDEXING-PLAN.md §D).
//
// Each logo becomes a nested <svg> cell with a <view id="c-<sym>"> over it, and a page shows one with
//   <img src="/coin-icons/sprite.svg?v=<hash>#c-btc">
// The fragment changes what is drawn, not what is fetched, so the browser downloads the file once.
// Gradient ids are prefixed per coin, because every logo now shares one document.
// The per-coin files stay: widgets (/embed/), og images and other sites still use them.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

// The grid is always square, so the file's own aspect ratio is 1:1 like every logo (object-fit: contain
// in app.css would otherwise letterbox a cell).
const CELL = 32, GAP = 8;

const cellFor = (sym, svg) => {
  const open = svg.match(/^<svg\b([^>]*)>/);
  if (!open || !svg.trimEnd().endsWith("</svg>")) throw new Error(`coin-icons/${sym}.svg: unexpected markup`);
  const attrs = open[1];
  const viewBox = (attrs.match(/\bviewBox="([^"]+)"/) || [])[1];
  if (!viewBox) throw new Error(`coin-icons/${sym}.svg: no viewBox`);
  // Keep presentation attributes of the root (fill="none", preserveAspectRatio); drop xmlns, size and ids.
  const keep = [...attrs.matchAll(/\s([\w:-]+)="([^"]*)"/g)]
    .filter(([, k]) => !/^(xmlns(:\w+)?|width|height|x|y|id|viewBox|version)$/.test(k))
    .map(([, k, v]) => ` ${k}="${v}"`).join("");
  let inner = svg.trimEnd().slice(open[0].length, -"</svg>".length);
  const p = `${sym}-`;
  inner = inner
    .replace(/\bid="([^"]+)"/g, (_, id) => `id="${p}${id}"`)
    .replace(/url\(\s*(['"]?)#([^)'"]+)\1\s*\)/g, (_, q, id) => `url(#${p}${id})`)
    .replace(/\b(xlink:)?href="#([^"]+)"/g, (_, x, id) => `${x || ""}href="#${p}${id}"`);
  return { viewBox, keep, inner };
};

// Writes coin-icons/sprite.svg for the coins marked `logo` and returns "/coin-icons/sprite.svg?v=<hash>".
// Output depends only on the logo files and the registry order, so rebuilding without changes is a no-op.
export function buildSprite(root, coins) {
  const withLogo = coins.filter(c => c.logo && existsSync(join(root, "coin-icons", `${c.sym.toLowerCase()}.svg`)));
  const COLS = Math.max(1, Math.ceil(Math.sqrt(withLogo.length)));
  const W = COLS * (CELL + GAP) - GAP, H = W;
  const parts = withLogo.map((c, i) => {
    const sym = c.sym.toLowerCase();
    const x = (i % COLS) * (CELL + GAP), y = Math.floor(i / COLS) * (CELL + GAP);
    const { viewBox, keep, inner } = cellFor(sym, readFileSync(join(root, "coin-icons", `${sym}.svg`), "utf8"));
    return `<view id="c-${sym}" viewBox="${x} ${y} ${CELL} ${CELL}"/>` +
      `<svg x="${x}" y="${y}" width="${CELL}" height="${CELL}" viewBox="${viewBox}"${keep}>${inner}</svg>`;
  });
  const out = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">` +
    `<!-- Generated by scripts/build-coin-pages.mjs from coin-icons/*.svg (scripts/lib/sprite.mjs). Do not edit. -->\n` +
    parts.join("\n") + `\n</svg>\n`;
  const file = join(root, "coin-icons", "sprite.svg");
  if (!existsSync(file) || readFileSync(file, "utf8") !== out) writeFileSync(file, out);
  return `/coin-icons/sprite.svg?v=${createHash("sha256").update(out).digest("hex").slice(0, 10)}`;
}
